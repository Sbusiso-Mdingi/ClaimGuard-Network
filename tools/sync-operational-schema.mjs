import { readFile, writeFile } from "node:fs/promises";

import {
  CANONICAL_OPERATIONAL_SCHEMA_VERSION,
} from "../packages/database/src/operational-schema.js";

const target = new URL(
  "../services/report-producer/src/claimguard_report_producer/operational_schema.py",
  import.meta.url,
);

const content = `# Generated by tools/sync-operational-schema.mjs.
CANONICAL_OPERATIONAL_SCHEMA_VERSION = "${CANONICAL_OPERATIONAL_SCHEMA_VERSION}"

CANONICAL_OPERATIONAL_MIGRATION_VERSION = int(
    CANONICAL_OPERATIONAL_SCHEMA_VERSION
)

DEFAULT_SUPPORTED_SCHEMA_VERSIONS = frozenset(
    {
        CANONICAL_OPERATIONAL_SCHEMA_VERSION,
    }
)
`;

if (process.argv.includes("--check")) {
  const existing = await readFile(target, "utf8");
  if (existing !== content) {
    throw new Error(
      "Operational schema bindings are stale. Run `npm run schema:sync`.",
    );
  }
} else {
  await writeFile(target, content, "utf8");
}